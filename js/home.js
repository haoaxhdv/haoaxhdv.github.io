/* ---------- Colorway: the visitor's suit dresses the whole page (control lives in the lining label) ---------- */
const suit = $('[data-suit]');
let swapToken = 0;
function setColorway(id, { focus = false, push = true } = {}) {
  const cw = COLORWAYS.find((c) => c.id === id) || COLORWAYS[0];
  root.dataset.cw = cw.id;
  $$('[data-swatches] [role="radio"]').forEach((b) => {
    const on = b.dataset.cw === cw.id;
    b.setAttribute('aria-checked', String(on));
    b.tabIndex = on ? 0 : -1;
    if (on && focus && b.closest('[data-swatches]').contains(document.activeElement)) b.focus();
  });
  $$('[data-way]').forEach((el) => (el.textContent = cw.label));
  $$('[data-buy]').forEach((a) => (a.href = cw.url));
  if (suit && suit.getAttribute('src') !== cw.img) {
    const token = ++swapToken;
    const next = new Image(); next.src = cw.img;
    suit.classList.add('is-swapping');
    const decoded = Promise.race([next.decode().catch(() => {}), new Promise((r) => setTimeout(r, 700))]);
    Promise.all([decoded, new Promise((r) => setTimeout(r, reduced ? 0 : 240))]).then(() => {
      if (token !== swapToken) return;
      suit.src = cw.img;
      suit.alt = `Dope Era Color Block Sweat Suit, ${cw.label} colorway: jacket and pants`;
      setTimeout(() => suit.classList.remove('is-swapping'), 30);
    });
  }
  store.set('de-cw', cw.id);
  if (push) { const u = new URL(location.href); u.searchParams.set('cw', cw.id); history.replaceState(null, '', u); }
}
$$('[data-swatches]').forEach((group) => {
  const radios = $$('[role="radio"]', group);
  radios.forEach((b, i) => {
    b.addEventListener('click', () => setColorway(b.dataset.cw));
    b.addEventListener('keydown', (e) => {
      const step = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key];
      if (!step) return;
      e.preventDefault();
      setColorway(radios[(i + step + radios.length) % radios.length].dataset.cw, { focus: true });
    });
  });
});
(window.requestIdleCallback || setTimeout)(() => COLORWAYS.forEach((c) => { new Image().src = c.img; }));

