/* ---------- Materials: tabs that re-skin the chapter ---------- */
const matSection = $('[data-mat-section]');
const tabs = $$('[role="tab"]', matSection);
function selectTab(tab, focus) {
  tabs.forEach((t) => {
    const on = t === tab;
    t.setAttribute('aria-selected', String(on)); t.tabIndex = on ? 0 : -1;
    const panel = document.getElementById(t.getAttribute('aria-controls'));
    panel.hidden = !on;
    if (on) { panel.classList.remove('is-in'); void panel.offsetWidth; panel.classList.add('is-in'); matSection.dataset.skin = panel.dataset.skin; }
  });
  if (focus) tab.focus();
}
tabs.forEach((t, i) => {
  t.addEventListener('click', () => selectTab(t));
  t.addEventListener('keydown', (e) => {
    const step = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key];
    if (e.key === 'Home') { e.preventDefault(); selectTab(tabs[0], true); }
    if (e.key === 'End') { e.preventDefault(); selectTab(tabs.at(-1), true); }
    if (!step) return;
    e.preventDefault(); selectTab(tabs[(i + step + tabs.length) % tabs.length], true);
  });
});
matSection.dataset.skin = ($('[role="tabpanel"]:not([hidden])', matSection) || {}).dataset?.skin || 'lettering';

