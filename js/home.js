const unzipRange = () => Math.max(1, unzip.offsetHeight - innerHeight);
function updateUnzip() {
  if (reduced) return;
  const p = clamp((scrollY - unzip.offsetTop) / unzipRange());
  unzipP = p;
  const W = street.clientWidth, H = street.clientHeight;
  let zy, zg, ax;
  if (p < 0.6) { const q = p / 0.6; zy = q * 100; zg = q * 18; ax = 0; }
  else { const q = clamp((p - 0.6) / 0.32); zy = 100; zg = 18 + q * 40; ax = q * 58; }
  unzip.style.setProperty('--zy', zy + '%');
  unzip.style.setProperty('--zg', zg + '%');
  unzip.style.setProperty('--ax', ax + '%');
  unzip.classList.toggle('is-moving', p > 0.01);
  unzip.classList.toggle('is-parting', p >= 0.6);
  unzip.classList.toggle('is-open', p >= 0.97);
  const cx = W / 2, py = Math.max(64, (zy / 100) * H);
  zl.setAttribute('x1', cx - (zg / 100) * W); zl.setAttribute('y1', 0); zl.setAttribute('x2', cx - (ax / 100) * W); zl.setAttribute('y2', py);
  zr.setAttribute('x1', cx + (zg / 100) * W); zr.setAttribute('y1', 0); zr.setAttribute('x2', cx + (ax / 100) * W); zr.setAttribute('y2', py);
  zc.setAttribute('x1', cx); zc.setAttribute('y1', py); zc.setAttribute('x2', cx); zc.setAttribute('y2', p >= 0.6 ? py : H);
  pull.style.setProperty('--pull-y', py + 'px');
  street.style.setProperty('--pull-y', py + 'px');
  reel.visible(p < 0.97);
}
