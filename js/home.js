/* ---------- The rack: one garment per hanger on a shared rail; the centred piece is selected ---------- */
const rack = $('[data-rack]');
const rtrack = $('[data-rtrack]', rack);
const items = $$('.rackr__item', rtrack);
const links = items.map((li) => $('.rackr__g', li));
const RACK = SHOOT.rack.items;
const rPrev = $('[data-rprev]', rack), rNext = $('[data-rnext]', rack);
const rName = $('[data-rname]', rack), rCount = $('[data-rcount]', rack), rGo = $('[data-rgo]', rack);
let cur = -1;
const centreOf = (li) => li.offsetLeft + li.offsetWidth / 2;
const nearestToCentre = () => { const c = rtrack.scrollLeft + rtrack.clientWidth / 2; let best = 0; items.forEach((li, i) => { if (Math.abs(centreOf(li) - c) < Math.abs(centreOf(items[best]) - c)) best = i; }); return best; };
function select(i) {
  if (i === cur) return;
  cur = i;
  items.forEach((li, j) => { li.classList.toggle('is-current', j === i); links[j].tabIndex = j === i ? 0 : -1; });
  const r = RACK[i];
  rName.textContent = r.name;
  rCount.textContent = `${String(i + 1).padStart(2, '0')} / ${RACK.length}`;
  rGo.href = r.url; rGo.setAttribute('aria-label', `View piece: ${r.name}`);
  rPrev.disabled = i === 0; rNext.disabled = i === items.length - 1;
}
// While the rail animates to a chosen piece, the pieces passing the centre don't take over the selection.
let holdSel = false, holdT = 0;
const release = () => { clearTimeout(holdT); holdSel = false; };
function go(i, { focus = false } = {}) {
  i = clamp(i, 0, items.length - 1);
  holdSel = true; clearTimeout(holdT);
  holdT = setTimeout(release, reduced ? 60 : 1400);
  rtrack.addEventListener('scrollend', () => setTimeout(release, 30), { once: true });
  rtrack.scrollTo({ left: centreOf(items[i]) - rtrack.clientWidth / 2, behavior: reduced ? 'auto' : 'smooth' });
  select(i);
  if (focus) links[i].focus({ preventScroll: true });
}
rPrev.addEventListener('click', () => go(cur - 1));
rNext.addEventListener('click', () => go(cur + 1));
// swipe / wheel / drag: whichever garment is centred becomes the selection
let rraf = 0;
rtrack.addEventListener('scroll', () => { if (holdSel) return; cancelAnimationFrame(rraf); rraf = requestAnimationFrame(() => select(nearestToCentre())); }, { passive: true });
// keyboard: the selected garment is the single tab stop; arrows move along the rail, Enter opens the piece
rtrack.addEventListener('keydown', (e) => {
  const k = { ArrowRight: cur + 1, ArrowLeft: cur - 1, Home: 0, End: items.length - 1 }[e.key];
  if (k === undefined) return;
  e.preventDefault(); go(k, { focus: true });
});
// a click on a neighbouring garment brings it to the centre; a click on the centred one opens it
let rdrag = null, dragged = false;
rtrack.addEventListener('click', (e) => {
  const a = e.target.closest('.rackr__g'); if (!a) return;
  if (dragged) { e.preventDefault(); dragged = false; return; }
  const i = links.indexOf(a);
  if (i !== cur) { e.preventDefault(); go(i); }
});
// mouse drag (touch uses native scrolling)
rtrack.addEventListener('pointerdown', (e) => { if (e.pointerType !== 'mouse' || e.button !== 0) return; rdrag = { x: e.clientX, left: rtrack.scrollLeft }; dragged = false; });
addEventListener('pointermove', (e) => {
  if (!rdrag) return;
  const dx = e.clientX - rdrag.x;
  if (!dragged && Math.abs(dx) > 5) { dragged = true; rack.classList.add('is-dragging'); }
  if (dragged) rtrack.scrollLeft = rdrag.left - dx;
});
addEventListener('pointerup', () => {
  if (!rdrag) return;
  rdrag = null;
  if (dragged) { rack.classList.remove('is-dragging'); go(nearestToCentre()); setTimeout(() => { dragged = false; }, 0); }
});
rtrack.addEventListener('dragstart', (e) => e.preventDefault());
// start on the hero piece, centred, without animating
const startAt = Math.max(0, RACK.findIndex((r) => r.front));
const centreStart = () => { rtrack.scrollLeft = centreOf(items[startAt]) - rtrack.clientWidth / 2; select(startAt); };
